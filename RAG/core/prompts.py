"""模型提示词模板

本文件是全项目**提示词的唯一出处**(不要再往别的模块里散写提示词字符串)。
按用途分四组,每组都写清了"对应课案哪一章的什么策略"和"输出契约是什么":

一、RAG 作答(基础篇「检索增强生成 · 提示词设计」)
    `SYSTEM_PROMPT`            生成阶段的行为边界(只依据资料、不编造、标注引用编号)
    `RAG_ANSWER_PROMPT`        带参考内容的回答模板(user 消息)
    `NO_EVIDENCE_REPLY`        一条没过阈值时的固定话术(不是提示词,是门控出口)

二、路由与 query 改写(优化篇「查询路由 / RAG 优化方法(query 改写)」)
    `ROUTER_PROMPT`            路由 + 选改写策略
    `HYDE_PROMPT`              假设问题检索(HyDE)
    `SUBQUERY_PROMPT`          子查询检索
    `BACKTRACK_PROMPT`         回溯问题检索
    `DIRECT_QA_PROMPT`         直答(不检索)
    `REWRITE_LABELS`           策略 → 中文标签(给日志/前端用)

三、最终回答质量评估(基础篇「系统评估 · 第四步:用大模型评估最终回答」)
    `EVALUATION_PROMPT`        LLM-as-judge,1~5 分

四、评估样本生成 + 两道质检(基础篇「系统评估 · 样本生成」)
    `QA_GENERATION_PROMPT`                  生成事实型问答样本
    `QUESTION_GROUNDEDNESS_CRITIQUE_PROMPT` 质检 1:问题能否仅凭上下文无歧义回答
    `QUESTION_STANDALONE_CRITIQUE_PROMPT`   质检 2:问题是否独立、完整、指代清晰

修改提示词时的三条硬约束
========================
1. **占位符只能由代码以关键字参数填充**(几乎都是 `str.format(...)`):
   - `{question}`:`llm/chat.py` 的 `route_query` / `rewrite_query` / 直答 / `llm_judge.py` 等;
   - `{context}` / `{answer}` / `{ground_truth}`:仅 `EVALUATION_PROMPT` 用。
   改占位符名必须同时改调用方,否则运行时 `KeyError`。
2. **正文里要用字面量花括号就必须写两遍**(`{{` / `}}`),否则 `.format()` 会当成占位符;
   本文件里 `ROUTER_PROMPT` 的 JSON 示例、`EVALUATION_PROMPT` 的输出格式、`QA_GENERATION_PROMPT`
   的 JSON 示例都是这种转义写法。
3. **提示词与课案不是逐字一致**(只有语义对齐):课案的 `STRATEGY_PROMPT` 本身是个坏 f-string
   (模块级 `{query}` 未定义,导入即 NameError),本项目把它并进了 `ROUTER_PROMPT`。
   对应关系与差异已登记在 README 的对齐表里;`tests/test_prompts.py` 只做"含关键词"断言,
   **没有逐字契约** —— 改措辞不会报错,但要自己保证语义不变。
"""

# ---------------------------------------------------------------------------
# 一、RAG 作答
# ---------------------------------------------------------------------------

# 生成阶段的 system 提示词(RAG 链路专用,直答路径不使用它)。
# 对应课案基础篇"提示词设计/抑制幻觉"一节。四条约束缺一不可:
# ① 只依据提供的资料;② 资料里没有的不编造;③ 资料不足就直接说"未找到相关票据"
# (而不是硬答 —— 这是"拒答"能力的来源);④ 标注引用编号,如 [1]。
# 编号由 `pipeline/rag_pipeline.py::_build_context` 生成(证据从 [1] 开始编号),
# 与 ④ 的格式**必须**对得上,否则前端点不到来源。
SYSTEM_PROMPT = (
    "你是一名专业的财务票据智能问答助手。请严格依据提供的票据资料回答用户问题,"
    "资料中没有的信息不要编造;若资料不足以回答,请直接说明未找到相关票据。"
    "回答简洁、准确,并标注引用的资料编号,如 [1]。"
)

# 带参考内容的回答模板(user 消息),与上面的 system 提示词配合使用。
# 由 `llm/chat.py::_messages` 以 `RAG_ANSWER_PROMPT.format(context=..., question=...)` 填充,
# 所以这里的 `{context}` / `{question}` 两个名字是**跨模块契约**。
# `context` 的实际形态("每条由元数据行和内容行组成")由
# `rag_pipeline._format_record` 决定:一行元数据(类型/票号/相关人/日期/金额/路线/对方)
# + 一行 `内容:`(优先 `ocr_text`,拿不到才退回 `semantic_text`)。
RAG_ANSWER_PROMPT = """请根据以下票据资料回答用户问题。

票据资料(每条由元数据行和内容行组成):
{context}

用户问题:
{question}
"""

# 智能路由提示词:一次调用同时决定"走不走检索"和"用哪种改写策略"。
# 对应优化篇「查询路由 + query 改写」两章,它们在本项目里被合并成一次 LLM 调用
# (课案是分开的两段逻辑;合并的理由:路由本来就顺带做一次理解,省一次往返)。
#
# 输出契约(**只输出一个 JSON**):
#   {"route": "RAG"|"DIRECT", "rewrite": "hyde"|"subquery"|"backtrack"|"direct"}
# 但代码并不强依赖严格 JSON:`llm/chat.py::route_query` 用两条正则去抠 `"route"` / `"rewrite"`,
# 抠不到就按安全默认值兜底(→ RAG + direct)。所以提示词里"请只输出如下 JSON"是**期望**,
# 不是硬约束 —— 这样网关/模型换了也不会让路由整段失效。
#
# 两段内容都值得留意:
# - 路由判定方向与代码兜底方向一致(无法确定 → RAG):宁可多检索,不要让模型凭空答金额/票号;
# - 四种改写策略的适用场景要和三个改写提示词 + `REWRITE_LABELS` 一一对应,
#   尤其 backtrack 是"把复杂问题**简化**",不是"补全隐含上下文"
#   (`tests/test_prompts.py::TestBacktrackSemantics` 钉住了这条语义,别改错方向)。
#
# 注意 `{{"route": "RAG", "rewrite": "direct"}}` 的双花括号是 `str.format` 的转义,
# 渲染后是单个花括号;这里唯一的占位符是 `{question}`。
ROUTER_PROMPT = """你是一个问答系统的智能路由器,负责两项判断:

第一,路由判断:该问题应由知识库检索回答(RAG),还是由大模型直接回答(DIRECT)?
1. 凡是询问金额、花费、费用、采购、报销、支付、日期、行程、路线、票号、人员、公司等与票据或财务记录相关的信息 → RAG
2. 只有纯粹的数学计算、生活常识、闲聊、通用百科等完全不需要任何票据资料的问题 → DIRECT
3. 无法确定时,一律返回 RAG
注意:宁可多走检索,不要由大模型凭空回答具体数据。

第二,若路由判断为 RAG,请为该问题选择一种 query 改写策略(检索时会同时保留直接检索):
- hyde: 假设问题检索 —— 问题口语化、模糊、缺少关键检索词时,先生成假设性答案文档再用它做语义检索
- subquery: 子查询检索 —— 问题包含多个条件、多个实体或多个时间段时,拆解成子问题分别检索
- backtrack: 回溯问题检索 —— 问题过于复杂、条件太多时,先把它简化为更基础、更易于检索的问题(如"各业务线收入构成和毛利率对比"简化为"各业务线收入和毛利率")
- direct: 直接检索 —— 问题清晰明确,原问题即可直接检索

用户问题:{question}

请只输出如下 JSON,不要输出任何其他内容:
{{"route": "RAG", "rewrite": "direct"}}"""

# 直答模板:route=DIRECT 时使用(纯计算/常识/闲聊)。
# 与 RAG 路径的两处差异,都是刻意的:
# ① **没有 system 提示词**(`llm/chat.py` 只发这一条 user 消息)—— "只依据资料作答"的约束
#    对直答没有意义,反而会让模型拒答常识问题;
# ② 没有资料、没有引用编号要求(答案里不该出现 `[1]`)。
# 输出契约:一段简洁准确的普通文本(非流式返回同时会带上 reasoning,由上层分开处理)。
DIRECT_QA_PROMPT = """请直接回答用户的问题,回答简洁、准确。

用户问题:
{question}"""

# ---------------------------------------------------------------------------
# 二、query 改写(三种策略,代码侧登记在 `llm/chat.py::REWRITE_PROMPTS`)
# ---------------------------------------------------------------------------

# HyDE(Hypothetical Document Embeddings,假设问题检索):
# 让模型**假设性**地写出一段"最可能出现在票据原文里的内容",再拿这段假文档去做向量检索。
# 适用:用户问题口语化、太短、缺少检索词(如"上个月去北京那趟花了多少"),原问题的向量
# 与票据文本的向量距离太远,先用模型把它"翻译"成票据口径的文本,再检索就准得多。
#
# 输出契约(**很关键**):只输出那一段假设性文本,100 字以内,**不要任何解释**。
# 这段文本不是给用户看的答案,而是"检索用 query" ——
# `llm/chat.py::rewrite_query` 把它整段作为一条 query 返回,
# `rag_pipeline` 再与**原问题并集**去双路召回(课案是替换,本项目是并集,差异已记 README)。
# 代码侧不做长度截断:模型写超了只是多花点 embedding token,不致命。
HYDE_PROMPT = """用户问题:{question}

请假设你就是票据资料库中的一份原始票据资料,针对该问题生成一段最可能出现在票据原文中的内容
(包含金额、日期、人员、公司、路线、票号等关键信息的假设性文本,100 字以内,只输出这段文本,不要任何解释)。"""

# 子查询检索:把"多条件/多实体/多时间段"的问题拆成若干独立子问题,各自去检索,
# 命中面比单条改写宽得多(如"对比张三和李四两个人今年的火车票费用"→ 两个子问题)。
#
# 输出契约:2~3 行,每行一个子问题,**除编号外不要输出别的内容**。
# 解析方是 `llm/chat.py::rewrite_query`:按行切 → `strip(" \t0123456789.、()()•-–")` 去掉
# 行首尾的编号与符号 → 空行丢掉 → **最多取 3 条**(与这里的 2~3 对齐)。
# 所以这里的"3"不只是提示词的软要求,也是代码硬上限,改这里要同步改代码。
SUBQUERY_PROMPT = """用户问题:{question}

请把该问题拆解为 2~3 个更简单、独立的子问题,每行一个子问题,不要输出编号以外的任何内容。"""

# 回溯问题检索(backtrack):把过于复杂、条件太多的查询**简化**成更基础、更易检索的问题。
# 注意语义方向:**简化/回退**,不是"补全隐含上下文 / 指代消解"—— 后者是另一类改写,
# `tests/test_prompts.py` 明确钉住"补全"不能出现在本提示词里。
#
# 输出契约:只输出简化后的问题本身(直接接在"简化问题:"后面,别带前缀、别解释)。
# 用 few-shot 给了一个例子(prompt 里的"业务线收入构成和毛利率对比"是课案原文的例子,
# 不是本项目票据场景的示例 —— 保留它是因为模型对 few-shot 格式的跟随比抽象描述更好)。
# 同样由 `rewrite_query` 整段作为一条 query 返回,与原问题并集检索。
BACKTRACK_PROMPT = """将以下复杂查询简化为一个更基础、更易于检索的问题,只输出简化后的问题即可。

例如:
问题:我需要了解公司各业务线的收入构成和毛利率对比情况。
简化问题:各业务线收入和毛利率

问题:{question}
简化问题:"""

# ---------------------------------------------------------------------------
# 三、门控出口 + 策略标签
# ---------------------------------------------------------------------------

# 保守回复话术:**不是提示词**,不经过 LLM。
# 触发条件:重排之后一条都没过 `RERANK_RELEVANCE_P` 阈值(`rag_pipeline` 里 `if not top_rows`),
# 此时链路选择"宁可不答也不编",直接把这段话术当答案下发,并写进缓存。
# 契约:`tests/test_prompts.py` 要求必须含"没有检索到/未找到"与"无法作答"两种表述 ——
# 也就是既要说明"没找到依据",又要说明"所以不回答"。
# 文案里还给了下一步指引(补充票号/日期/人员/公司),这是"拒答也要可用"的设计。
NO_EVIDENCE_REPLY = (
    "抱歉,我在票据知识库中没有检索到与您的问题足够相关的可靠依据,为避免提供不准确的信息,这个问题我暂时无法作答。"
    "您可以补充票号、日期、人员或公司名称等更多线索后再次提问,我会尽力为您核实。"
)

# 改写策略 → 中文标签。用途有两个:
# ① 日志(如 `[路由] rag | 改写策略=假设问题检索(HyDE)`);
# ② 事件流透给前端展示(`rag_pipeline` 里 `REWRITE_LABELS[method]`)。
#
# 契约:**键集合必须与 `llm/chat.py::REWRITE_PROMPTS`(hyde/subquery/backtrack)
# 加上 direct 完全一致**(`tests/test_prompts.py::test_rewrite_labels_cover_all_strategies` 钉住)。
# 又因为 `rag_pipeline` 会直接 `REWRITE_LABELS[method]` 下标取用,
# **新增一种改写策略时要同步改三处**:策略提示词常量、`REWRITE_PROMPTS`、以及这里的标签,
# 漏掉最后这处会直接 KeyError 打断整个问答。
REWRITE_LABELS = {
    "hyde": "假设问题检索(HyDE)",
    "subquery": "子查询检索",
    "backtrack": "回溯问题检索",
    "direct": "直接检索",
}

# ============================================================
# 系统评估用提示词(基础篇「系统评估」)
# ============================================================

# 最终回答质量评估:1~5 分,输出必须包含 Feedback 与 [RESULT]
# 对应课案「系统评估 · 第四步:使用大模型评估最终回答」——LLM-as-judge:
# 给"问题 + 待评回答 + 满分参考答案 + 评分细则",让模型给分并写理由。
#
# 输出契约(**解析方强依赖**):
#     Feedback: <针对标准的反馈> [RESULT] <1~5 的整数>
# 解析方是 `evaluation/llm_judge.py::parse_result_score`,它的正则是
# `[\[【]\s*RESULT\s*[\]】]\s*\**\s*(\d+)` —— 所以:
# - `[RESULT]` 标记**必须有**(提示词里三次强调,还专门写了一条"确保输出包含 [RESULT]");
# - 中括号全角/半角、markdown 加粗都兼容,但**换了别的标记(如 `得分:`)就解析不出来**;
# - 分数越界(>5 或 <1)或解析失败会返回 None,由调用方决定记 NaN 还是跳过。
#
# 两个使用上的注意:
# ① 课案明确说过"EVALUATION_PROMPT 只评估最终回答质量,**不能替代**召回/重排指标",
#    所以它是补充信号,分阶段指标仍以 `evaluation/stage_metrics.py` 为准;
# ② 提示词里的 `{{针对标准的反馈}}` / `{{1 到 5 的整数}}` 是 `str.format` 转义的字面量花括号
#    (测试里专门有一条 `test_evaluation_prompt_formats_without_error` 守这个);
#    四个占位符 `{context}` / `{question}` / `{answer}` / `{ground_truth}` 缺一不可。
# 打分口径按"是否符合事实、是否准确"分五档,与参考答案(得分 5)对齐比较。
EVALUATION_PROMPT = """## 任务描述：
这里提供了一个问题、待评估的回答、得分为 5 的参考答案，以及表示评估标准的评分细则。
1. 根据给定的评分细则，严格评估回答的质量，撰写详细的反馈，不进行一般性评价。
2. 在撰写反馈后，给出一个 1 到 5 的整数分数，需参考评分细则。
3. 输出格式应如下：“Feedback: {{针对标准的反馈}} [RESULT] {{1 到 5 的整数}}”
4. 请勿生成其他开场、结尾或解释内容。确保输出包含 [RESULT]。

## 参考文章：
{context}

## 问题：
{question}

## 待评估的回答：
{answer}

## 参考答案（得分 5）：
{ground_truth}

## 评分细则：
[回答是否基于参考答案正确、准确且符合事实？]
得分 1：回答完全不正确、不准确和/或不符合事实。
得分 2：回答大部分不正确、不准确和/或不符合事实。
得分 3：回答部分正确、准确和/或符合事实。
得分 4：回答大部分正确、准确且符合事实。
得分 5：回答完全正确、准确且符合事实。

## 反馈：
"""

# 样本生成的第一道质检:问题能否仅凭上下文无歧义回答
# 要拦的缺陷:上下文里根本没有该信息,模型却编出一个"看起来合理"的问题 ⇒
# 这条样本后期永远答不对,扣的是**链路**的分,实际是样本的锅(静默污染指标)。
#
# 输出契约(文本模板,不是 JSON):
#     回答:::
#     评价：<评分理由>
#     总评分：<1~5>
# 解析方是 `evaluation/sample_gen.py::parse_critique`:它**先试 JSON、失败再按正则抠**
# ("总评分"允许全角/半角冒号与 markdown 加粗),所以这里写文本格式就够、不必强求 JSON;
# 但"总评分"三个字与"评价"两个字是正则的锚点,**不能改措辞**。
# 通过门槛:`passes_quality` 要求两道质检都 >= 5 分(`MIN_SCORE = 5`),否则重新生成(最多 3 次)。
QUESTION_GROUNDEDNESS_CRITIQUE_PROMPT = """你将获得一个上下文和一个问题。
你的任务是给出一个“总评分”，评估该问题是否能够通过给定的上下文明确无歧义地回答。
请在1到5分之间进行评分，其中1表示完全无法根据上下文回答该问题，5表示能够清晰且无歧义地根据上下文回答该问题。
请按以下格式给出你的回答：
回答:::
评价：（你对评分的理由，文本形式）
总评分：（你给出的评分，范围为1到5的数字）
你的回答必须包含“评价”和“总评分”的内容。
现在是问题和上下文内容：
问题：{question}

上下文：{context}

回答::: """

# 样本生成的第二道质检:问题是否独立、完整、指代清晰
# 要拦的缺陷:生成出「它的金额是多少?」「这张票多少钱?」这种依赖生成时上下文的指代 ——
# 作为评估集里独立的一条毫无意义。
#
# 这里有一句容易被误读、但**非常重要**的界定:
#   "这里评估的是'能否理解问题',不是'不查询知识库能否回答问题'。"
# 也就是:问题**允许**需要查库才能回答(评估集本来就是检索题),
# 只要求它自身把"查什么"说清楚。反过来写会让质检把合格的样本全毙掉。
#
# 输出契约与解析方式同上(回答:::/评价：/总评分：,由 `parse_critique` 解析)。
# 评分档写了 1/3/5 三档并配了正反例(反例是"这张票/该文档"这种指代,
# 正例带票号与"人名+日期+路线"的完整条件),最后一句"专业术语、票据编号或业务缩写不会降低分数"
# 是为了防止模型把"ticket_001 这种编号看不懂"当成不独立而误扣分。
QUESTION_STANDALONE_CRITIQUE_PROMPT = """你将获得一个问题。
你的任务是评估该问题是否独立、完整、指代清晰。
这里评估的是“能否理解问题”，不是“不查询知识库能否回答问题”。
请在1到5分之间评分：
1分：问题严重依赖未提供的上下文，单独看无法确定询问对象。
例如：“这张票多少钱？”“该文档中的金额是多少？”
3分：问题基本可以理解，但仍然存在部分模糊指代或缺少必要条件。
5分：问题自身完整、指代清晰，即使答案需要查询知识库，
也能够明确知道需要查询什么。
例如：
“票据ticket_001的金额是多少？”
“张三2026年3月5日从北京南到上海虹桥的高铁票金额是多少？”
专业术语、票据编号或业务缩写不会降低分数，
只要问题本身的查询对象和条件清晰即可。
请严格按照以下格式输出：
回答:::
评价：（评分理由）
总评分：（1到5的整数）

现在是问题：
问题：{question}

回答::: """

# 事实型问答样本生成。
# 说明:课案 HTML 只给出了调用方式 `qa_generation_prompt.format(context=context)`
# 与输出约定(JSON 里取 "事实型问题" / "答案" 两个键),提示词正文未导出;
# 这里按课案的两条质检标准(能仅凭上下文回答、问题独立完整)补写,措辞与评分口径保持一致。
#
# 输出契约(**中文键**,解析方按字面取值):
#     {"事实型问题": "...", "答案": "..."}
# 解析方是 `script/generate_eval_samples.py::generate_one`:它会先剥 ``` 围栏与 `json` 前缀
# 再 `json.loads`,然后取 `payload["事实型问题"]` / `payload["答案"]` —— 键名写错就直接 KeyError
# 被当成"解析失败"重试。所以这三条输出要求(只输出 JSON / 两个中文键 / 不要别的内容)都不能动。
#
# 提示词里前置了两条生成要求(能仅凭资料回答、不许出现"这张票"这类指代),
# 用意是**降低返回工** —— 生成完还要过上面两道质检,门槛是 5 分,
# 把质检标准写进生成提示词能少抽几次签。`{context}` 传的是票据的 `ocr_text` 全文。
QA_GENERATION_PROMPT = """你是一个财务票据问答样本生成助手。

请基于下面这份票据资料,生成 1 个“事实型问题”和它对应的“答案”:
- 问题必须能仅凭该资料明确无歧义地回答,不要问资料里没有的信息;
- 问题必须独立、完整、指代清晰,不要出现“这张票”“该文档”这类依赖上下文的说法;
- 答案只写资料中出现的事实(金额、日期、人员、公司、票号、路线等),不要推测或补全;
- 只输出 JSON,格式为 {{"事实型问题": "...", "答案": "..."}},不要输出其他任何内容。

票据资料:
{context}"""
