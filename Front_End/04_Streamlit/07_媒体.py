# 一、用 Pillow 现场生成图片
# -----------------------------------------------------------------------------
# 为什么要生成而不是"找一张图"？
#   因为本项目约定不联网、不下载素材。用代码生成图片有三个好处：
#   ① 完全离线可复现；② 演示了 Pillow 这个常见的图像处理库；
#   ③ st.image 支持直接吃 PIL.Image 对象，正好一起演示。
