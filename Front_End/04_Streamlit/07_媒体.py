# 二、用标准库 wave + numpy 现场合成一段音频
# =============================================================================
def create_wav_file(path: Path, seconds: float = 2.0, sample_rate: int = 22050) -> Path:
    """
    生成一段可以播放的 WAV 音频文件（正弦波 + 淡入淡出，避免爆音）。

    参数：
        path        输出文件路径
        seconds     时长（秒）
        sample_rate 采样率（Hz）。22050 是常见的语音/提示音采样率。

    原理：WAV 就是「采样点序列 + 头部描述」。
          wave 模块负责写头部，我们只需要把每个采样点的幅度算出来写进去。
    """
    total_samples = int(seconds * sample_rate)
    # 用 numpy 一次性算出所有采样点，比 Python 循环快得多
    t = np.linspace(0, seconds, total_samples, endpoint=False)

    # 三个音叠加：A4(440Hz) 主音 + 五度音 + 八度音，听起来像一个"提示音"
    wave_data = (
        0.6 * np.sin(2 * math.pi * 440.0 * t)
        + 0.25 * np.sin(2 * math.pi * 660.0 * t)
        + 0.15 * np.sin(2 * math.pi * 880.0 * t)
    )

    # 淡入淡出包络：前 10% 渐强，后 20% 渐弱，避免开头/结尾的"啪"声
    envelope = np.ones(total_samples)
    fade_in = int(total_samples * 0.10)
    fade_out = int(total_samples * 0.20)
    envelope[:fade_in] = np.linspace(0.0, 1.0, fade_in)
    envelope[-fade_out:] = np.linspace(1.0, 0.0, fade_out)

    samples = wave_data * envelope
    # 归一化到 int16 的范围（-32768 ~ 32767）
    pcm = (samples * 32767 * 0.8).astype(np.int16)

    # 用 wave 模块写文件：1 声道、2 字节/采样、采样率 sample_rate。
    # pcm 是 numpy 的 int16 数组，tobytes() 得到的正是 WAV 需要的
    # 「小端序、有符号 16 位整数」字节流，所以不需要额外用 struct 打包。
    with wave.open(str(path), "wb") as wav_file:
        wav_file.setnchannels(1)          # 单声道
        wav_file.setsampwidth(2)          # 每个采样 2 字节 = 16 位
        wav_file.setframerate(sample_rate)
        wav_file.writeframes(pcm.tobytes())

    return path


