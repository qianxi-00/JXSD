def create_demo_image() -> Image.Image:
    """画一张带渐变背景、图形和文字的示例图片，返回 PIL.Image 对象。"""
    width, height = 640, 400
    img = Image.new("RGB", (width, height), (255, 255, 255))
    draw = ImageDraw.Draw(img)

    # ① 背景：自上而下的线性渐变（逐行画横线）
    for y in range(height):
        t = y / height
        r = int(79 + (168 - 79) * t)      # 从 #4f46e5 渐变到 #a855f7
        g = int(70 + (85 - 70) * t)
        b = int(229 + (247 - 229) * t)
        draw.line([(0, y), (width, y)], fill=(r, g, b))

    # ② 画几个半透明的圆（Pillow 的 RGB 模式没有 alpha，用叠加亮度的方式模拟）
    for i, radius in enumerate((90, 60, 35)):
        cx = 120 + i * 200
        cy = 150
        shade = 255 - i * 30
        draw.ellipse(
            [cx - radius, cy - radius, cx + radius, cy + radius],
            fill=(shade, shade, 255),
            outline=(255, 255, 255),
            width=3,
        )

    # ③ 画一个圆角矩形按钮
    draw.rounded_rectangle([60, 270, 580, 340], radius=16, fill=(255, 255, 255))

    # ④ 写文字。优先用一个确定存在的字体，找不到就退回 Pillow 的默认位图字体，
    #    这样在【任何】机器上都不会因为"字体文件不存在"而报错。
    title = "Pillow 现场生成的示例图片"
    subtitle = "640 x 400  ·  RGB  ·  保存为 PNG"
    font_title = None
    font_sub = None
    for candidate in (
        r"C:\Windows\Fonts\msyh.ttc",      # 微软雅黑
        r"C:\Windows\Fonts\simhei.ttf",    # 黑体
        r"C:\Windows\Fonts\arial.ttf",
    ):
        if Path(candidate).exists():
            try:
                font_title = ImageFont.truetype(candidate, 28)
                font_sub = ImageFont.truetype(candidate, 18)
                break
            except OSError:
                # 字体文件存在但解析失败，继续尝试下一个
                continue

    if font_title is None:
        # 一个字体都没找到，用 Pillow 内置的默认字体（不支持中文，所以写英文）
        title = "Image generated by Pillow"
        subtitle = "640 x 400  |  RGB  |  saved as PNG"
        font_title = ImageFont.load_default()
        font_sub = ImageFont.load_default()

    # anchor="mm" 表示以文字中心点定位，方便居中
    draw.text((width // 2, 150), title, fill=(255, 255, 255), font=font_title, anchor="mm")
    draw.text((width // 2, 305), subtitle, fill=(79, 70, 229), font=font_sub, anchor="mm")

    return img


def create_chart_image() -> Image.Image:
    """
    用 Pillow 的绘图 API 手绘一张柱状图。

    为什么要「手绘」而不是用 matplotlib？
    因为这个函数的目的是演示 **Pillow 本身能画什么**（`ImageDraw` 的
    line / rectangle / ellipse / text），而不是演示画图表 ——
    真正要画图表请用 `05_图表.py` 里的 `st.pyplot(fig)`（matplotlib）
    或 `st.bar_chart`，那些才是专业工具。

    另外这也能说明一个重要事实：**Streamlit 的 `st.image` 接受"任何 PIL.Image 对象"**，
    所以你可以用 Pillow 在运行时生成/加工图片（加水印、裁剪、拼图、生成占位图），
    完全不需要提前准备素材文件。
    """
    width, height = 640, 360
    img = Image.new("RGB", (width, height), (255, 255, 255))
    draw = ImageDraw.Draw(img)

    # 坐标轴
    left, top, right, bottom = 70, 40, 600, 300
    draw.line([(left, bottom), (right, bottom)], fill=(120, 120, 120), width=2)   # x 轴
    draw.line([(left, top), (left, bottom)], fill=(120, 120, 120), width=2)       # y 轴

    # 数据（6 个月的销售额）
    labels = ["1月", "2月", "3月", "4月", "5月", "6月"]
    values = [120, 180, 150, 220, 260, 300]
    max_value = max(values)
    plot_height = bottom - top - 20
    bar_width = (right - left - 40) // len(values) - 12

    for i, (label, value) in enumerate(zip(labels, values)):
        x0 = left + 20 + i * (bar_width + 12)
        bar_height = int(plot_height * value / max_value)
        y0 = bottom - bar_height
        # 柱体
        draw.rectangle([x0, y0, x0 + bar_width, bottom - 1], fill=(79, 70, 229))
        # 数值标注
        draw.text((x0 + bar_width // 2, y0 - 12), str(value), fill=(60, 60, 60), anchor="mm")
        # 月份标签
        draw.text((x0 + bar_width // 2, bottom + 18), label, fill=(90, 90, 90), anchor="mm")

    draw.text((width // 2, 18), "月度销售额（万元）— 用 Pillow 手绘", fill=(40, 40, 40), anchor="mm")
    return img


